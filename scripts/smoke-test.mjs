import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:3000';
await mkdir('.checks', { recursive: true });
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, deviceScaleFactor: 1 });
const page = await context.newPage();
await page.emulateMedia({ reducedMotion: 'reduce' });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
let testId;
const request = context.request;
try {
  await page.goto(base, { waitUntil: 'networkidle' });
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Наша фильмотека.');
  await expect(page.locator('.movie-card')).toHaveCount(15);
  const initial = await (await request.get(base + '/api/movies')).json();
  assert.equal(initial.length, 77);
  assert.equal(initial.find(movie => movie.id === 'film-45').adeleRating, 0);
  await page.screenshot({ path: '.checks/desktop-dark.png' });
  console.log('PASS: initial collection, ratings, desktop rendering');

  const search = page.getByRole('textbox', { name: 'Поиск фильмов' });
  await search.fill('зеленая');
  await expect(page.locator('.movie-card')).toHaveCount(1);
  await expect(page.locator('.card-title')).toHaveText('Зелёная книга');
  await search.fill('совсем-несуществующий-фильм');
  await expect(page.getByText('В этой сцене пока пусто')).toBeVisible();
  await search.fill('');
  await page.getByLabel('Фильтр по жанру').selectOption('Ужасы');
  await expect(page.locator('.card-meta').first()).toContainText('Ужасы');
  await page.getByLabel('Фильтр по жанру').selectOption('all');
  await page.getByLabel('Сортировка фильмов').selectOption('rating');
  await expect(page.locator('.card-title').first()).toHaveText('Джон Уик');
  await page.getByLabel('Сортировка фильмов').selectOption('added');
  await page.getByRole('button', { name: 'Дополнительные фильтры' }).click();
  await page.getByLabel('Наша оценка', { exact: true }).selectOption('9');
  const nineCount = await page.locator('.movie-card').count();
  assert(nineCount > 0 && nineCount < 15);
  await page.getByLabel('Наша оценка', { exact: true }).selectOption('all');
  await page.getByRole('button', { name: 'Дополнительные фильтры' }).click();
  await page.getByRole('button', { name: 'Таблица', exact: true }).click();
  await expect(page.locator('.movie-table tbody tr')).toHaveCount(15);
  console.log('PASS: Cyrillic search, empty state, genre/rating filters, sorting, table view');

  await page.getByRole('button', { name: 'Добавить фильм', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.locator('input[placeholder="Например, Интерстеллар"]').fill('Тестовый киновечер');
  await dialog.locator('input[placeholder="Interstellar"]').fill('A Test Movie');
  await dialog.getByRole('button', { name: 'Драма', exact: true }).click();
  await dialog.getByRole('textbox', { name: 'Краткое описание' }).fill('Тестовое описание для проверки сохранения в PostgreSQL.');
  await dialog.getByRole('button', { name: 'Просмотрен', exact: true }).click();
  await dialog.getByLabel(/Оценка Адели/).fill('9.5');
  await dialog.getByLabel(/Оценка Ромы/).fill('8');
  await dialog.getByRole('button', { name: 'Добавить фильм', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  const afterCreate = await (await request.get(base + '/api/movies')).json();
  const created = afterCreate.find(movie => movie.title === 'Тестовый киновечер');
  assert(created);
  testId = created.id;
  assert.equal(created.adeleRating, 9.5);
  await page.reload({ waitUntil: 'networkidle' });
  await search.fill('Тестовый киновечер');
  await expect(page.locator('.table-film')).toHaveCount(1);
  await page.getByRole('button', { name: 'Редактировать «Тестовый киновечер»', exact: true }).click();
  await dialog.locator('input[placeholder="Например, Интерстеллар"]').fill('Тестовый киновечер — обновлён');
  await dialog.getByLabel(/Оценка Адели/).fill('0');
  await dialog.getByRole('checkbox', { name: /В избранное/ }).check();
  await dialog.getByRole('button', { name: 'Сохранить изменения' }).click();
  await expect(dialog).not.toBeVisible();
  const updated = (await (await request.get(base + '/api/movies')).json()).find(movie => movie.id === testId);
  assert.equal(updated.adeleRating, 0);
  assert.equal(updated.favorite, true);
  await page.getByRole('button', { name: 'Редактировать «Тестовый киновечер — обновлён»', exact: true }).click();
  await dialog.getByRole('button', { name: 'Удалить фильм', exact: true }).click();
  await dialog.getByRole('button', { name: 'Да, удалить', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  testId = undefined;
  await search.fill('');
  console.log('PASS: create, edit, zero/fractional ratings, favorite, reload persistence, delete confirmation');

  const invalid = await request.post(base + '/api/movies', { data: { title: '', year: 2024 } });
  assert.equal(invalid.status(), 400);
  const unknown = await request.patch(base + '/api/movies/not-found', { data: { favorite: true } });
  assert.equal(unknown.status(), 404);
  await page.getByRole('button', { name: 'Карточки', exact: true }).click();
  await page.getByRole('button', { name: 'Светлая', exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  await page.reload({ waitUntil: 'networkidle' });
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  await page.screenshot({ path: '.checks/desktop-light.png' });
  await page.getByRole('button', { name: 'Тёмная', exact: true }).click();
  await page.getByRole('button', { name: 'Открыть фильм', exact: true }).click();
  await expect(page.locator('#details-title')).toHaveText('Интерстеллар');
  await page.screenshot({ path: '.checks/movie-details.png' });
  await page.getByRole('button', { name: 'Закрыть окно', exact: true }).click();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Скачать коллекцию в CSV' }).click();
  const exported = await download;
  assert.equal(exported.suggestedFilename(), 'kadr-films.csv');
  assert.equal(await exported.failure(), null);
  await page.keyboard.press('Control+k');
  await expect(search).toBeFocused();
  console.log('PASS: API validation, light theme persistence, movie details, CSV export, keyboard shortcut');

  await page.getByRole('button', { name: 'Показать ещё', exact: true }).click();
  await expect(page.locator('.movie-card')).toHaveCount(30);
  await page.getByRole('button', { name: 'Показать ещё', exact: true }).click();
  await page.getByRole('button', { name: 'Показать ещё', exact: true }).click();
  await page.getByRole('button', { name: 'Показать ещё', exact: true }).click();
  await page.getByRole('button', { name: 'Показать ещё', exact: true }).click();
  await expect(page.locator('.movie-card')).toHaveCount(77);
  console.log('PASS: pagination loads all 77 films');

  const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, deviceScaleFactor: 1 });
  const mobile = await mobileContext.newPage();
  await mobile.emulateMedia({ reducedMotion: 'reduce' });
  mobile.on('pageerror', error => errors.push(error.message));
  await mobile.goto(base, { waitUntil: 'networkidle' });
  assert(await mobile.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile horizontal overflow');
  await mobile.screenshot({ path: '.checks/mobile-dark.png', fullPage: true });
  await mobile.getByRole('button', { name: 'Открыть меню' }).click();
  await mobile.locator('.main-nav').getByRole('button', { name: /В планах/ }).click();
  await expect(mobile.locator('.sidebar')).not.toHaveClass(/mobile-open/);
  await expect(mobile.locator('.movie-card').first().locator('.poster-status')).toHaveText('В планах');
  await mobile.getByRole('button', { name: 'Открыть фильм «Гипнотик»', exact: true }).click();
  await expect(mobile.locator('#details-title')).toHaveText('Гипнотик');
  await mobile.screenshot({ path: '.checks/mobile-details.png' });
  await mobile.getByRole('button', { name: 'Закрыть окно', exact: true }).click();
  for (const width of [360, 600, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `Horizontal overflow at ${width}px`);
  }
  await mobileContext.close();
  assert.deepEqual(errors, [], 'Browser JavaScript errors');
  console.log('PASS: mobile navigation, mobile movie details, responsive widths, no JavaScript errors');
  console.log('ALL CHECKS PASSED');
} finally {
  if (testId) await request.delete(base + '/api/movies/' + testId);
  await browser.close();
}
